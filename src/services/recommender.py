from dataclasses import dataclass, field
from typing import List

from src.models import ActivityType, BusinessScale, Opf, TaxRegime


@dataclass
class Answers:
    activity: ActivityType
    scale: BusinessScale
    founders_count: int
    need_investments: bool
    unlimited_liability_ok: bool


@dataclass
class Recommendation:
    opf: Opf
    reason: str
    tax_regime: TaxRegime
    tax_comment: str
    pros: List[str] = field(default_factory=list)
    cons: List[str] = field(default_factory=list)
    next_steps: List[str] = field(default_factory=list)
    risk_level: str = "средний"
    alternatives: List[str] = field(default_factory=list)


def recommend(answers: Answers) -> Recommendation:
    """Возвращает структурированную рекомендацию по ОПФ."""
    # Самозанятость
    if (
        answers.founders_count == 1
        and answers.scale == BusinessScale.SMALL
        and not answers.need_investments
        and answers.activity in (ActivityType.SERVICES, ActivityType.IT, ActivityType.TRADE)
        and answers.unlimited_liability_ok
    ):
        return Recommendation(
            opf=Opf.SELF_EMPLOYED,
            reason=(
                "Для единственного исполнителя малого бизнеса в сфере услуг, IT или торговли "
                "оптимален режим самозанятости (НПД). Регистрация мгновенная через приложение "
                "«Мой налог», нет обязательных взносов в ПФР/ФОМС при отсутствии дохода, "
                "налог 4–6 %. Подходит при годовом доходе до 2,4 млн ₽."
            ),
            tax_regime=TaxRegime.NPD,
            tax_comment="Налог на профессиональный доход: 4 % с доходов от физлиц, 6 % от юрлиц и ИП.",
            pros=[
                "Мгновенная регистрация без визита в налоговую",
                "Нет обязательных страховых взносов при нулевом доходе",
                "Простая отчётность через приложение",
                "Низкая налоговая нагрузка",
            ],
            cons=[
                "Лимит дохода 2,4 млн ₽ в год",
                "Нельзя нанимать работников по трудовому договору",
                "Не подходит для некоторых видов деятельности (продажа подакцизных товаров и др.)",
                "Нет возможности работать по УСН/ОСНО",
            ],
            next_steps=[
                "Зарегистрироваться в приложении «Мой налог»",
                "Проверить, подходит ли ваш вид деятельности под НПД",
                "Вести учёт доходов в приложении",
                "При превышении лимита или найме сотрудников — перейти на ИП",
            ],
            risk_level="низкий",
            alternatives=["ИП на УСН", "ИП на патенте"],
        )

    # ИП
    if (
        answers.founders_count == 1
        and answers.scale in (BusinessScale.SMALL, BusinessScale.MEDIUM)
        and not answers.need_investments
        and answers.unlimited_liability_ok
    ):
        tax = TaxRegime.USN_INCOME
        tax_comment = "Рекомендуется УСН «Доходы» 6 % (или 1–6 % по региональной ставке)."
        if answers.activity == ActivityType.PRODUCTION:
            tax = TaxRegime.USN_INCOME_EXPENSE
            tax_comment = "При производстве часто выгоднее УСН «Доходы минус расходы» 15 %."
        elif answers.activity == ActivityType.TRADE and answers.scale == BusinessScale.SMALL:
            tax = TaxRegime.PSN
            tax_comment = "Для розничной торговли в ряде регионов доступен патент (ПСН)."

        return Recommendation(
            opf=Opf.IP,
            reason=(
                "Индивидуальный предприниматель — оптимальный выбор для единственного собственника "
                f"бизнеса масштаба «{answers.scale.label.lower()}». Регистрация проще и дешевле, чем у ООО, "
                "налоговая и бухгалтерская отчётность легче. Вы несёте полную имущественную ответственность "
                "по обязательствам."
            ),
            tax_regime=tax,
            tax_comment=tax_comment,
            pros=[
                "Простая и быстрая регистрация (3 рабочих дня)",
                "Минимальный пакет документов",
                "Возможность применять УСН, ПСН, ЕСХН",
                "Свободное распоряжение прибылью",
                "Меньше требований к ведению бухгалтерии",
            ],
            cons=[
                "Полная (неограниченная) ответственность личным имуществом",
                "Сложнее привлекать инвесторов",
                "Ограничения по некоторым лицензируемым видам деятельности",
                "Обязательные страховые взносы «за себя» даже при отсутствии дохода",
            ],
            next_steps=[
                "Подготовить паспорт и ИНН",
                "Выбрать систему налогообложения при регистрации",
                "Подать заявление через Госуслуги или МФЦ",
                "Открыть расчётный счёт (рекомендуется)",
                "При необходимости — зарегистрироваться в качестве работодателя",
            ],
            risk_level="средний" if answers.scale == BusinessScale.SMALL else "повышенный",
            alternatives=["Самозанятость (если подходит по лимитам)", "ООО"],
        )

    # ООО
    if (
        answers.founders_count > 1
        or answers.need_investments
        or answers.scale == BusinessScale.MEDIUM
        or not answers.unlimited_liability_ok
    ) and answers.scale != BusinessScale.LARGE:
        return Recommendation(
            opf=Opf.LLC,
            reason=(
                "Общество с ограниченной ответственностью — наиболее универсальная и популярная форма "
                "для малого и среднего бизнеса. Подходит при наличии партнёров, необходимости ограничить "
                "личную ответственность и привлечь инвестиции (доли в уставном капитале). "
                "Минимальный уставный капитал — 10 000 ₽."
            ),
            tax_regime=TaxRegime.USN if answers.scale == BusinessScale.SMALL else TaxRegime.USN_INCOME_EXPENSE,
            tax_comment=(
                "Для малого бизнеса чаще выбирают УСН. При существенных расходах — «Доходы минус расходы». "
                "Крупные обороты или работа с НДС — ОСНО."
            ),
            pros=[
                "Ограниченная ответственность участников (в пределах вклада)",
                "Возможность нескольких учредителей",
                "Гибкое распределение долей и прибыли",
                "Привлекательность для инвесторов и банков",
                "Возможность продать долю или выйти из бизнеса",
            ],
            cons=[
                "Более сложная регистрация и отчётность, чем у ИП",
                "Обязательное ведение бухгалтерского учёта",
                "Необходимость формировать и хранить корпоративные документы",
                "Вывод прибыли — через дивиденды (НДФЛ 13/15 %)",
            ],
            next_steps=[
                "Подготовить решение/протокол о создании и устав",
                "Определить размер и распределение уставного капитала",
                "Подать документы в ФНС (можно онлайн через Госуслуги)",
                "Открыть расчётный счёт и внести уставный капитал",
                "Назначить генерального директора и при необходимости главного бухгалтера",
            ],
            risk_level="низкий",
            alternatives=["ИП (если один учредитель и готовность к рискам)", "АО (при крупных инвестициях)"],
        )

    # АО
    return Recommendation(
        opf=Opf.JSC,
        reason=(
            "Акционерное общество рекомендуется для крупного бизнеса и случаев, когда планируется "
            "привлечение значительных инвестиций через выпуск акций. Акционеры несут ограниченную "
            "ответственность. Публичное АО (ПАО) может размещать акции на бирже."
        ),
        tax_regime=TaxRegime.OSNO,
        tax_comment=(
            "Крупные компании обычно работают на ОСНО (НДС + налог на прибыль 25 %). "
            "При определённых условиях возможна УСН, но лимиты по выручке и численности ограничены."
        ),
        pros=[
            "Возможность привлекать капитал через выпуск акций",
            "Ограниченная ответственность акционеров",
            "Высокий уровень доверия со стороны крупных контрагентов и банков",
            "Возможность публичного размещения (для ПАО)",
            "Гибкие механизмы корпоративного управления",
        ],
        cons=[
            "Сложная и дорогостоящая регистрация и сопровождение",
            "Обязательный аудит в ряде случаев",
            "Жёсткие требования к раскрытию информации (особенно для ПАО)",
            "Высокие административные расходы",
            "Минимальный уставный капитал выше, чем у ООО (для непубличных — 10 000 ₽, для ПАО — 100 000 ₽)",
        ],
        next_steps=[
            "Определить тип АО (непубличное / публичное)",
            "Подготовить устав, решение о создании, договор о создании",
            "Зарегистрировать выпуск акций в Банке России (при необходимости)",
            "Подать документы на государственную регистрацию",
            "Сформировать органы управления (совет директоров, правление и т.д.)",
        ],
        risk_level="низкий",
        alternatives=["ООО (если масштаб позволяет и нет нужды в акциях)"],
    )